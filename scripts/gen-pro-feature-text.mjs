// Builds src/settings/v3/proFeatureText.gen.ts (the name and the plain "what it
// does" of every Professional feature) from docs/mockups/pro-features.md.
// Run: node scripts/gen-pro-feature-text.mjs   (a unit test checks it is current)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = new URL('docs/mockups/pro-features.md', root)
const target = new URL('src/settings/v3/proFeatureText.gen.ts', root)

/** Rows `| \`id\` | Name | What it does |` as { id, name, does }. */
export function parseProFeatureText(markdown) {
  const out = []
  for (const line of markdown.split(/\r?\n/)) {
    const m = /^\|\s*`([^`]+)`\s*\|\s*(.*?)\s*\|\s*(.*?)\s*\|\s*$/.exec(line)
    if (m) out.push({ id: m[1], name: m[2], does: m[3] })
  }
  return out
}

export function renderProFeatureText(entries) {
  const q = (s) => JSON.stringify(s)
  const rows = entries
    .map((e) => `  ${q(e.id)}: [${q(e.name)}, ${q(e.does)}],`)
    .join('\n')
  return `// Generated by scripts/gen-pro-feature-text.mjs from docs/mockups/pro-features.md. Do not edit.
/** id -> [name, what it does] (English; other languages fall back to it). */
export const PRO_FEATURE_TEXT: Record<string, readonly [string, string]> = {
${rows}
}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const entries = parseProFeatureText(readFileSync(source, 'utf8'))
  writeFileSync(target, renderProFeatureText(entries))
  console.log(`Wrote ${entries.length} texts.`)
}
