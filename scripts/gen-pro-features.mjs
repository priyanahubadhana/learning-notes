// Builds src/settings/proFeatures.gen.ts from docs/mockups/pro-features.md.
// Run: node scripts/gen-pro-features.mjs   (the unit test checks it is current)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = new URL('docs/mockups/pro-features.md', root)
const target = new URL('src/settings/proFeatures.gen.ts', root)

/** Ids (first table column, in backticks) with their group heading. */
export function parseProFeatures(markdown) {
  const out = []
  let group = ''
  for (const line of markdown.split(/\r?\n/)) {
    const heading = /^##\s+(.*?)\s*(?:\(\d+\))?\s*$/.exec(line)
    if (heading) {
      group = heading[1]
      continue
    }
    const row = /^\|\s*`([^`]+)`\s*\|/.exec(line)
    if (row && group) out.push({ id: row[1], group })
  }
  return out
}

/** The text of the generated file. */
export function renderProFeatures(entries) {
  const q = (s) => JSON.stringify(s)
  const rows = entries
    .map((e) => `  { id: ${q(e.id)}, group: ${q(e.group)} },`)
    .join('\n')
  return `// Generated by scripts/gen-pro-features.mjs from docs/mockups/pro-features.md. Do not edit.
export const PRO_FEATURES = [
${rows}
] as const

export type ProFeatureId = (typeof PRO_FEATURES)[number]['id']
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const entries = parseProFeatures(readFileSync(source, 'utf8'))
  writeFileSync(target, renderProFeatures(entries))
  console.log(`Wrote ${entries.length} features.`)
}
