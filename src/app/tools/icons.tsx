export type IconName = keyof typeof ICONS

/** A thin (1.6 px) line icon, decorative: the button carries the name. */
export function Icon({
  name,
  size = 20,
  className,
}: {
  name: IconName
  size?: number
  className?: string
}) {
  const Glyph = ICONS[name]
  return (
    <Glyph
      aria-hidden
      focusable={false}
      size={size}
      strokeWidth={1.6}
      className={className}
    />
  )
}
